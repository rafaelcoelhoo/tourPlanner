const DICTS: Record<Lang, Record<Key, string>> = { pt, en, es };
const STORAGE = "lang";
let current: Lang = "pt";
export const currentLang = (): Lang => current;

const detect = (): Lang => {
  const saved = localStorage.getItem(STORAGE);
  if (saved === "pt" || saved === "en" || saved === "es") return saved;
  const n = navigator.language.slice(0, 2);
  return n === "es" ? "es" : n === "en" ? "en" : "pt";
};

const cap = (s: string): string => s.replace(/\./g, "").replace(/^./, (c) => c.toLocaleUpperCase());

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  weekdayShort: (i: number) => string;
  weekdayLong: (i: number) => string;
  weekdayInitial: (i: number) => string;
  monthName: (m: number) => string;
  fmtDate: (iso: string) => string;
  periodLabel: (p: Period) => string;
  languageName: (code: string, fallback: string) => string;
  violation: (code: ViolationCode) => string;
}

const I18nCtx = createContext<Ctx | null>(null);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    current = detect();
    return current;
  });
  useEffect(() => {
    current = lang;
    document.documentElement.lang = lang;
    document.title = DICTS[lang].appName;
  }, [lang]);

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[lang];
    const t: Ctx["t"] = (key, vars) => (vars ? Object.entries(vars).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), dict[key]) : dict[key]);
    const weekday = (i: number, style: "short" | "long") =>
      cap(new Intl.DateTimeFormat(lang, { weekday: style, timeZone: "UTC" }).format(new Date(Date.UTC(2024, 0, 1 + i))));
    const weekdayShort = (i: number) => weekday(i, "short");
    return {
      lang,
      setLang: (l) => {
        localStorage.setItem(STORAGE, l);
        current = l;
        setLangState(l);
      },
      t,
      weekdayShort,
      weekdayLong: (i) => weekday(i, "long"),
      weekdayInitial: (i) => weekdayShort(i).slice(0, 1),
      monthName: (m) => cap(new Intl.DateTimeFormat(lang, { month: "long", timeZone: "UTC" }).format(new Date(Date.UTC(2024, m - 1, 1)))),
      fmtDate: (iso) => {
        const idx = (new Date(`${iso}T00:00:00Z`).getUTCDay() + 6) % 7;
        return `${weekdayShort(idx)} ${iso.slice(8)}/${iso.slice(5, 7)}`;
      },
      periodLabel: (p) => dict[`per.${p}`],
      languageName: (code, fallback) => (`lang.${code}` in dict ? dict[`lang.${code}` as Key] : fallback),
      violation: (code) => dict[`viol.${code}`],
    };
  }, [lang]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
};

export const useI18n = (): Ctx => {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("I18nProvider em falta");
  return c;
};

export const LanguageSelect = () => {
  const { lang, setLang, t } = useI18n();
  return (
    <select value={lang} onChange={(e) => setLang(e.target.value as Lang)} aria-label={t("languageAria")} className="lang-select">
      {LANGS.map((l) => <option key={l.code} value={l.code}>{l.label}</option>)}
    </select>
  );
};
